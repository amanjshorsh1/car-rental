class Translator:
    """Looks up a text by key for a language (falls back to English, then the key)."""
    DEFAULT = "en"

    def __init__(self, texts=TRANSLATIONS):
        self._texts = texts

    @property
    def languages(self):
        return tuple(self._texts)

    def is_supported(self, code):
        return code in self._texts

    def direction(self, code):
        return "rtl" if code == "ku" else "ltr"

    def t(self, key, lang, params=None):
        text = self._texts.get(lang, {}).get(key)
        if text is None:
            text = self._texts[self.DEFAULT].get(key, key)
        if params:
            try:
                text = text.format(**params)
            except (KeyError, IndexError):
                pass
        return text
